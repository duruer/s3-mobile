"""Convert an Anime4K mpv user shader (CNN upscaler, e.g. Anime4K_Upscale_CNN_x2_S.glsl from
https://github.com/bloc97/Anime4K, MIT) into GLSL ES 3.00 fragment shaders for the Android presenter
(port/crates/s3-android/src/anime4k.rs). Usage: python -I tools/anime4k_to_gles.py IN.glsl OUT.rs

Supported shape (the x2 S/M/L "Conv-4x3x3x*" + "Depth-to-Space" chain): every conv pass binds one texture and
samples it with `<name>_texOff(vec2(x, y))`; the last pass binds MAIN + the last conv texture and returns the
residual + MAIN. Each pass becomes one fragment shader: conv passes read `u_tex` at texel centres (`u_pt` = 1 /
size), the depth-to-space pass reads `u_last` / `u_main`.
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
license_lines = []
for line in src.splitlines():
    if line.startswith('//!'):
        break
    license_lines.append(line)

passes = re.split(r'(?m)^(?=//!DESC)', src)
passes = [p for p in passes if p.startswith('//!DESC')]

out = []
conv = []
for p in passes:
    meta = dict()
    binds = re.findall(r'^//!BIND (\S+)', p, re.M)
    desc = re.search(r'^//!DESC (.*)$', p, re.M).group(1)
    body = '\n'.join(l for l in p.splitlines() if not l.startswith('//!'))
    if 'Depth-to-Space' in desc:
        continue
    assert len(binds) == 1, binds
    name = binds[0]
    body = body.replace(f'{name}_texOff(', 'TEX(')
    assert 'texOff' not in body and '_tex(' not in body, body[:200]
    conv.append((desc, body))

head = '''#version 300 es
precision highp float;
uniform sampler2D u_tex;
uniform vec2 u_pt;
in vec2 v_uv;
out vec4 o;
#define TEX(off) texture(u_tex, v_uv + (off) * u_pt)
'''
shaders = []
for desc, body in conv:
    shaders.append((desc, head + body.strip() + '\nvoid main() { o = hook(); }\n'))

final = '''#version 300 es
precision highp float;
uniform sampler2D u_last;
uniform sampler2D u_main;
uniform vec2 u_last_size;
in vec2 v_uv;
out vec4 o;
void main() {
    vec2 f0 = fract(v_uv * u_last_size);
    ivec2 i0 = ivec2(f0 * vec2(2.0));
    vec4 t = texture(u_last, (vec2(0.5) - f0) / u_last_size + v_uv);
    float c0 = t[i0.y * 2 + i0.x];
    o = vec4(texture(u_main, v_uv).rgb + vec3(c0), 1.0);
}
'''

with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('//! Anime4K CNN x2 upscaler shaders (generated by tools/anime4k_to_gles.py from\n')
    f.write('//! Anime4K_Upscale_CNN_x2_S.glsl, https://github.com/bloc97/Anime4K v3.2). Do not edit by hand.\n')
    f.write('//!\n')
    for l in license_lines:
        f.write('//! ' + l.lstrip('/ ').rstrip() + '\n' if l.strip() else '//!\n')
    f.write('\n/// Convolution passes, in order (input: the game frame, then each previous pass; RGBA16F outputs).\n')
    f.write('pub const CONV: [&str; %d] = [\n' % len(shaders))
    for desc, s in shaders:
        f.write('    // %s\n    r#"%s"#,\n' % (desc, s))
    f.write('];\n\n/// Depth-to-space: 2x output = bilinear game frame + the last pass\'s residual.\n')
    f.write('pub const DEPTH_TO_SPACE: &str = r#"%s"#;\n' % final)
print(len(shaders), 'conv passes')
