/// New value of a [`SPRITE_SITES`] entry.
pub fn sprite_site_value(orig: u32) -> u32 {
    match SPRITE_ARRAYS.iter().position(|&a| a == orig) {
        Some(i) => GFX_SIZE + i as u32 * SPRITE_BUCKETS * 4,
        None if orig == ORIG_BUCKETS + 1 => SPRITE_BUCKETS + 1,
        None => SPRITE_BUCKETS,
    }
}

/// New `gfx` allocation size (the bucket arrays behind the original object).
pub const fn gfx_size_new() -> u32 {
    GFX_SIZE + SPRITE_ARRAYS.len() as u32 * SPRITE_BUCKETS * 4
}

/// Every code change of the resolution patch as (address, original bytes, new bytes), in a fixed order: snapshot
/// tail moves, row stride, sprite buckets, `gfx` size. Pure (no game bytes beyond the original values of the
/// patched immediates).
pub fn code_patches() -> Vec<(u32, Vec<u8>, Vec<u8>)> {
    let le = |v: u32| v.to_le_bytes().to_vec();
    let d = snap_delta();
    let mut out = Vec::new();
    for &(a, off, v) in SNAP_TAIL_SITES {
        out.push((a + off, le(v), le(v.wrapping_add(d))));
    }
    for a in STRIDE_SHL_SITES {
        out.push((a + 2, vec![6], vec![7]));
    }
    for (a, off, v, n) in STRIDE_INDEX_SITES {
        debug_assert_eq!(v, n * ORIG_ROWS);
        out.push((a + off, le(v), le(n * SNAP_ROWS)));
    }
    for (a, off, v, n) in STRIDE_DISP_SITES {
        let add = (n * (SNAP_ROWS - ORIG_ROWS) as i32 * SNAP_CELL as i32) as u32;
        out.push((a + off, le(v), le(v.wrapping_add(add))));
    }
    for (a, off, v) in SPRITE_SITES {
        out.push((a + off, le(v), le(sprite_site_value(v))));
    }
    out.push((GFX_ALLOC_SITE.0 + GFX_ALLOC_SITE.1, le(GFX_SIZE), le(gfx_size_new())));
    out
}

/// Apply [`code_patches`] to raw guest memory (all or nothing; `Err` names the first site whose bytes differ).
/// Used by [`patch_snapshot`] and by the fast-path tests (which run the patched code).
pub fn apply_code_patches(mem: &mut s3_cpu::GuestMemory) -> Result<(), String> {
    let p = code_patches();
    for (a, old, _) in &p {
        let cur = mem.read_bytes(*a, old.len());
        if &cur != old {
            return Err(format!("res: patch site {a:#x}: expected {old:02x?}, found {cur:02x?}"));
        }
    }
    for (a, _, new) in &p {
        mem.write_bytes(*a, new);
    }
    Ok(())
}

