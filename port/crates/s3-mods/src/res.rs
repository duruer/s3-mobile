// ---------------------------------------------------------------- state

/// Runtime state (`m.state::<ResState>()`).
#[derive(Debug, Default)]
pub struct ResState {
    /// Hooks + snapshot patch installed.
    pub installed: bool,
    /// The snapshot grid was enlarged (code patched).
    pub snap_patched: bool,
    /// Size `0x42ce90` was asked for (non-standard): the next `SetDisplayMode` call site uses it.
    pub pending_mode: Option<(u32, u32)>,
    /// Custom size currently applied by us (layout + mode).
    pub applied: Option<(u32, u32)>,
    /// Size the renderer should switch to (set by the zoom logic every slice; `None` = leave the game alone).
    pub target: Option<(u32, u32)>,
    /// Display mode to use while `target` is active: the largest zoom size for the window aspect, so zoom steps
    /// only change the layout and the presented ("logical") size, not the mode (fast path).
    pub target_mode: Option<(u32, u32)>,
    /// Display mode we set (physical surface size).
    pub mode: Option<(u32, u32)>,
    /// `IDirectDraw2*` seen at the game's SetDisplayMode call (for logical-size calls).
    pub ddraw2: u32,
    /// Frames to skip after a fast switch until the logic thread made a snapshot for the new view size.
    pub settle_frames: u32,
    /// Keep this screen point (fractions of the frame) fixed over the next switch (pinch centre).
    pub anchor: Option<(f32, f32)>,
    /// `anchor.0` is a fraction of the map view instead of the frame (UI mode A with the panel shown at its own
    /// scale, `display::PanelSplit`: the panel keeps its screen width, the map part is scaled).
    pub anchor_map: bool,
    /// Number of switches done (stats / tests).
    pub switches: u32,
    /// `now_ms` of the last switch.
    pub last_switch_ms: u64,
    /// Landscape buffer / text DIB sizes requested at the last display setup (debug).
    pub landscape: Option<(u32, u32)>,
    pub text_dib: Option<(u32, u32)>,
    /// Frames after a switch that still get a forced full landscape redraw.
    pub redraw_frames: u32,
    /// Render frames seen by the switch hook (in-game frames).
    pub frames: u64,
    pub last_frame_ms: u64,
}

/// Frames with a forced full landscape redraw after a switch `cur -> want`. Each such frame redraws the whole
/// landscape (100-280 ms on the phone-size view), which made pinch zoom stutter: one frame is enough when the view
/// grows, none when it only shrinks (the landscape buffer already holds the smaller view; verified with
/// screenshots of in/out pinches, 2026-11-07). Env `S3_RES_REDRAW=N` / `S3_RES_REDRAW_SHRINK=N` override.
fn redraw_frames_after(cur: (u32, u32), want: (u32, u32)) -> u32 {
    let env = |k: &str| std::env::var(k).ok().and_then(|v| v.parse::<u32>().ok());
    let shrink = want.0 <= cur.0 && want.1 <= cur.1;
    if shrink {
        env("S3_RES_REDRAW_SHRINK").unwrap_or(0)
    } else {
        env("S3_RES_REDRAW").unwrap_or(1)
    }
}

fn trace() -> bool {
    std::env::var_os("S3_RES_TRACE").is_some()
}

/// Currently applied custom size (game pixels), if any.
pub fn applied(m: &mut Machine) -> Option<(u32, u32)> {
    m.state::<ResState>().borrow_mut().applied
}

/// Set the wanted size (`None` = no custom resolution; the standard size of the current variant is restored
/// if a custom one was applied). Applied by the render-thread hook at the next in-game frame.
pub fn set_target(m: &mut Machine, t: Option<(u32, u32)>) {
    set_target_mode(m, t, t);
}

/// Like [`set_target`] with the display mode to use (`mode` >= `t`; zoom passes its largest level so zoom
/// steps take the fast path).
pub fn set_target_mode(m: &mut Machine, t: Option<(u32, u32)>, mode: Option<(u32, u32)>) {
    let st = m.state::<ResState>();
    let mut s = st.borrow_mut();
    s.target = t.map(|(w, h)| clamp_size(w, h));
    s.target_mode = match (s.target, mode) {
        (Some((w, h)), Some((mw, mh))) => {
            let (mw, mh) = clamp_size(mw, mh);
            Some((mw.max(w), mh.max(h)))
        }
        (t, _) => t,
    };
}

/// Is a game frame being rendered (switch hook seen within the last second)?
pub fn in_game(m: &mut Machine) -> bool {
    let now = m.real_ms();
    let s = m.state::<ResState>();
    let s = s.borrow_mut();
    s.frames > 0 && now.saturating_sub(s.last_frame_ms) < 1000
}

/// [`in_game`] for showing the last frame: also true for up to 10 s without a new game frame while the shown
/// frame has a custom (non-standard) size. A big zoom step can keep the render thread busy for over a second
/// (full landscape redraw; the layout globals already have the next size while the old frame is still shown);
/// the 1 s rule then dropped the Classic panel split for that time and the panel jumped to the frame's scale
/// (flicker, 2026-11-08). Menus use standard sizes.
pub fn in_game_frame(m: &mut Machine) -> bool {
    if in_game(m) {
        return true;
    }
    let now = m.real_ms();
    let (frames, last) = {
        let s = m.state::<ResState>();
        let s = s.borrow_mut();
        (s.frames, s.last_frame_ms)
    };
    let size = m.last_frame_size();
    frames > 0
        && now.saturating_sub(last) < 10_000
        && size.0 > 0
        && !is_standard(size.0, size.1)
}

/// Is a resolution switch still being processed by the game (`[0x7dfd44] != 0`)?
pub fn switch_pending(m: &Machine) -> bool {
    m.mem.read_u32(RES_REQUEST) != 0
}

// ---------------------------------------------------------------- install

/// Enlarge the render snapshot grid to [`SNAP_COLS`] x [`SNAP_ROWS`] and the sprite lists to [`SPRITE_BUCKETS`]
/// buckets (code patch, see module docs).
pub fn patch_snapshot(m: &mut Machine) -> Result<(), String> {
    let p = code_patches();
    // Check every site first (all or nothing).
    for (a, old, _) in &p {
        let cur = m.mem.read_bytes(*a, old.len());
        if &cur != old {
            return Err(format!("res: patch site {a:#x}: expected {old:02x?}, found {cur:02x?}"));
        }
    }
    for (a, old, new) in &p {
        crate::patchset::patch_bytes(m, *a, old, new)?;
    }
    Ok(())
}

/// Install the resolution patch (GOG exe). Hooks are always installed with the GOG patch set (so every peer has
/// the same heap layout); custom sizes are only used while `settings.res.enabled`.
pub fn install(m: &mut Machine) -> Result<(), String> {
    patch_snapshot(m)?;
    {
        let st = m.state::<ResState>();
        let mut s = st.borrow_mut();
        s.installed = true;
        s.snap_patched = true;
    }
    hooks::add_hook(m, FN_DISPLAY_SWITCH, "res:display-switch", |c: &mut HookCtx| {
        let (w, h) = (c.arg(0), c.arg(1));
        let custom = !is_standard(w, h);
        if trace() {
            let ra = c.return_address();
            eprintln!("res: 0x42ce90({w}, {h}) from {ra:#x} custom {custom}");
        }
        c.m.state::<ResState>().borrow_mut().pending_mode = custom.then_some((w, h));
        HookFlow::Continue
    });
    for a in SETMODE_CALLS {
        hooks::add_hook(m, a, "res:set-display-mode", |c: &mut HookCtx| {
            let esp0 = c.esp();
            let this = c.m.mem.read_u32(esp0);
            let p = {
                let st = c.m.state::<ResState>();
                let mut s = st.borrow_mut();
                s.ddraw2 = this;
                s.pending_mode.take()
            };
            let esp = c.esp();
            if let Some((w, h)) = p {
                let (ow, oh) = (c.m.mem.read_u32(esp + 4), c.m.mem.read_u32(esp + 8));
                c.m.mem.write_u32(esp + 4, w);
                c.m.mem.write_u32(esp + 8, h);
                if trace() {
                    eprintln!("res: SetDisplayMode {ow}x{oh} -> {w}x{h}");
                }
            }
            // Every real mode change of the game (menus: 800x600, game start: the registry size) goes through here.
            let set = (c.m.mem.read_u32(esp + 4), c.m.mem.read_u32(esp + 8));
            c.m.state::<ResState>().borrow_mut().mode = Some(set);
            HookFlow::Continue
        });
    }
    hooks::add_hook(m, FN_LANDSCAPE_INIT, "res:landscape-max", |c: &mut HookCtx| {
        // Called by the display setup (0x42e430) at game start: make the ring buffer big enough for every size.
        let ra = c.return_address();
        if !(0x0042_e430..0x0042_f7e0).contains(&ra) {
            return HookFlow::Continue;
        }
        let esp = c.esp();
        let (w, h) = (c.m.mem.read_u32(esp + 4), c.m.mem.read_u32(esp + 8));
        let mw = MAX_W + c.m.mem.read_u32(L_LANDSCAPE_MARGIN_W);
        let mh = MAX_H + c.m.mem.read_u32(L_LANDSCAPE_MARGIN_H);
        let (nw, nh) = (w.max(mw), h.max(mh));
        c.m.mem.write_u32(esp + 4, nw);
        c.m.mem.write_u32(esp + 8, nh);
        c.m.state::<ResState>().borrow_mut().landscape = Some((nw, nh));
        if trace() {
            eprintln!("res: landscape buffer {w}x{h} -> {nw}x{nh} (from {ra:#x})");
        }
        HookFlow::Continue
    });
    hooks::add_hook(m, FN_TEXT_DIB, "res:text-dib-max", |c: &mut HookCtx| {
        let esp = c.esp();
        let (w, h) = (c.m.mem.read_u32(esp + 4), c.m.mem.read_u32(esp + 8));
        let (nw, nh) = (w.max(MAX_W), h.max(MAX_H));
        c.m.mem.write_u32(esp + 4, nw);
        c.m.mem.write_u32(esp + 8, nh);
        c.m.state::<ResState>().borrow_mut().text_dib = Some((nw, nh));
        if trace() {
            eprintln!("res: text DIB {w}x{h} -> {nw}x{nh}");
        }
        HookFlow::Continue
    });
    hooks::add_hook(m, FN_RUNTIME_SWITCH, "res:switch", switch_hook);
    if trace() {
        for (a, n) in [(0x0053_db30u32, "logic-tick"), (0x004c_74f0, "game-switch-1"), (0x004c_75ae, "game-switch-2"), (0x004c_767a, "game-switch-3"), (0x004c_6d70, "layout")] {
            hooks::add_hook(m, a, "res:trace", move |c: &mut HookCtx| {
                static N: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);
                let k = N.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                if k < 5 || k % 500 == 0 || c.m.mem.read_u32(RES_REQUEST) != 0 {
                    let r = c.m.mem.read_u32(RES_REQUEST);
                    let mw = c.m.mem.read_u32(L_MAP_W);
                    let t = c.m.current_tid();
                    eprintln!("res-trace: {n} #{k} tid {t} req {r:#x} mapw {mw}");
                }
                HookFlow::Continue
            });
        }
    }
    m.log(LogLevel::Info, &format!("mods: res: snapshot grid {SNAP_COLS}x{SNAP_ROWS}, {SPRITE_BUCKETS} sprite buckets, sizes up to {MAX_W}x{MAX_H}"));
    Ok(())
}

/// `0x4c7490` entry (render thread, every in-game frame, before the game's own F1-F3 check).
fn switch_hook(c: &mut HookCtx) -> HookFlow {
    let now = c.m.real_ms();
    let gfx = c.reg(ECX);
    let snap = c.arg(0);
    let (target, applied, anchor, anchor_map) = {
        let st = c.m.state::<ResState>();
        let mut s = st.borrow_mut();
        s.frames += 1;
        s.last_frame_ms = now;
        (s.target, s.applied, s.anchor, s.anchor_map)
    };
    if trace() {
        let last = c.m.state::<ResState>().borrow_mut().last_switch_ms;
        if last > 0 && now.saturating_sub(last) < 3000 {
            let r = |o: u32| c.m.mem.read_u32(snap + o);
            eprintln!("res-frame: t {now} cam {},{} prev {},{} req {:#x} glob {:#x}", r(4), r(8), r(0xc), r(0x10), r(0xa0), c.m.mem.read_u32(RES_REQUEST));
        }
    }
    if trace() && c.m.state::<ResState>().borrow_mut().frames % 300 == 1 {
        // Fill level of the fixed-size render lists after the previous frame (they are reset later in this frame,
        // `0x4b2da7`): sprite nodes (incl. one tail node per bucket), hit list `0x7ade12` (10000 entries).
        let r = |o: u32| c.m.mem.read_u32(gfx + o);
        let (l1, l2, l3) = (r(0x1425c), r(0x4b530), r(0x5f584));
        let hits = c.m.mem.read_u32(0x007d_fd60);
        eprintln!("res: lists sprite {l1}/4000 {l2}/8000 {l3}/4000 hits {hits}/10000");
    }
    // A switch (ours or F1-F3) is still being processed: let the game finish it.
    if c.m.mem.read_u32(RES_REQUEST) != 0 || c.m.mem.read_u32(snap + 0xa0) != 0 {
        return HookFlow::Continue;
    }
    // The display setup caches the map view rectangle in the landscape object; UI mode B changes the layout
    // afterwards (full-screen map, panel peek), which left a black band with a zigzag edge after F1-F3 (the
    // landscape was only drawn as wide as the cached rectangle). Keep it in sync and redraw when it changed.
    let synced = sync_view_rects(c.m, gfx);
    let cur = (c.m.mem.read_u32(L_SCREEN_W), c.m.mem.read_u32(L_SCREEN_H));
    let (target_mode, mode, settle) = {
        let st = c.m.state::<ResState>();
        let s = st.borrow_mut();
        (s.target_mode, s.mode, s.settle_frames)
    };
    // After a fast switch: skip frames until the logic thread's snapshot matches the new view (else one frame is
    // drawn from a snapshot of the old size).
    if settle > 0 {
        let matches = snapshot_matches(c.m, snap);
        let st = c.m.state::<ResState>();
        let mut s = st.borrow_mut();
        if !matches {
            s.settle_frames -= 1;
            drop(s);
            return c.return_from_function(1, 1);
        }
        s.settle_frames = 0;
    }
    // Force a full landscape redraw (previous camera far away, what the logic thread's acknowledgement does via
    // gd+0x2d254) on the first frames after a switch / view change whose snapshot already has the new view size
    // (a redraw from a snapshot of the old size left a black band with a zigzag edge).
    {
        let st = c.m.state::<ResState>();
        let mut s = st.borrow_mut();
        if synced {
            s.redraw_frames = s.redraw_frames.max(2);
        }
        if s.redraw_frames > 0 && snapshot_matches(c.m, snap) {
            s.redraw_frames -= 1;
            drop(s);
            c.m.mem.write_u32(snap + 0xc, 10_000_000);
            c.m.mem.write_u32(snap + 0x10, 10_000_000);
        }
    }
    let (want, want_mode) = match target {
        Some(t) => (t, target_mode.unwrap_or(t)),
        None => match applied {
            // Custom size turned off: back to the variant's standard size.
            Some(_) => {
                let v = variant_for(cur.1);
                ((v.w, v.h), (v.w, v.h))
            }
            None => return HookFlow::Continue,
        },
    };
    let fast = mode == Some(want_mode) && applied.is_some();
    if want == cur && fast {
        fix_map_width(c.m, want.0);
        return HookFlow::Continue;
    }
    // Camera: keep the anchored screen point over the same world point. Without an anchor (game start, F1-F3)
    // keep the view centre: the game centres the castle for the old (narrow) view, and keeping the camera's
    // top-left corner put it in the upper-left part of a wide view (user report 2026-11-07).
    let gd = crate::ui_hud_game::gd(c.m);
    if let (Some(g), Some((fx, fy))) = (gd, anchor.or(Some((0.5, 0.5)))) {
        let old_pw = c.m.mem.read_u32(L_PANEL_W) as f32;
        let new_pw = if old_pw == 0.0 { 0.0 } else { variant_for_mode(c.m, want.1).panel_w as f32 };
        let (cx, cy) = (c.m.mem.read_u32(g + GD_CAM_X) as i32, c.m.mem.read_u32(g + GD_CAM_Y) as i32);
        let (nx, ny) = if anchor_map && anchor.is_some() {
            crate::zoom::anchor_camera_map((cx, cy), (fx, fy), cur, want, old_pw, new_pw)
        } else {
            crate::zoom::anchor_camera((cx, cy), (fx, fy), cur, want, old_pw, new_pw)
        };
        c.m.mem.write_u32(g + GD_CAM_X, nx.max(0) as u32);
        c.m.mem.write_u32(g + GD_CAM_Y, ny.max(0) as u32);
    }
    let old_variant = c.m.mem.read_u32(L_RES);
    let hud_full = c.m.mem.read_u32(L_PANEL_W) == 0;
    write_layout(c.m, want.0, want.1);
    if hud_full {
        // UI mode B keeps its full-screen map (its panel hook re-applies it too; avoid one narrow frame).
        c.m.mem.write_u32(L_PANEL_W, 0);
        c.m.mem.write_u32(L_MAP_W, want.0);
    }
    let mut ack = true;
    if fast {
        // Fast path: same display mode, only the layout and the presented size change.
        update_view_rects(c.m, gfx);
        set_logical(c.m, want);
        // The logic acknowledgement (0x53db67) rebuilds the minimap (size depends on the variant), clamps the
        // camera and forces a redraw; only needed when the variant changes.
        ack = variant_for_mode(c.m, want.1).index != old_variant;
        if !ack {
            clamp_camera(c.m, gd);
        }
    } else {
        // Mode set: the display setup (0x42e430, run by the game after the mode change) creates its render
        // surfaces from the layout globals, so it must see the full mode size (VERIFIED: with the zoom size there,
        // later bigger zoom steps were clipped to it). Then switch the layout to the zoom size.
        write_layout(c.m, want_mode.0, want_mode.1);
        if hud_full {
            c.m.mem.write_u32(L_PANEL_W, 0);
            c.m.mem.write_u32(L_MAP_W, want_mode.0);
        }
        c.m.state::<ResState>().borrow_mut().pending_mode = (!is_standard(want_mode.0, want_mode.1)).then_some(want_mode);
        crate::call::call_thiscall(c.m, FN_DISPLAY_SWITCH, gfx, &[want_mode.0, want_mode.1, 16, 0, 0]);
        c.m.state::<ResState>().borrow_mut().pending_mode = None;
        write_layout(c.m, want.0, want.1);
        if hud_full {
            c.m.mem.write_u32(L_PANEL_W, 0);
            c.m.mem.write_u32(L_MAP_W, want.0);
        }
        // The setup stored the mode-size rectangles; use the zoom size.
        let gfx_now = gfx;
        update_view_rects(c.m, gfx_now);
        set_logical(c.m, want);
    }
    // The panel is only redrawn when dirty (map pixels would stay in the panel area otherwise).
    if let Some(g) = gd {
        c.m.mem.write_u32(g + 0x2d27c, 1);
    }
    if ack {
        // The F1-F3 key handler (0x525b5b) releases one token of the semaphore `[0x7a800c]` that the logic
        // thread's acknowledgement (0x53db80, after seeing 0xfa) waits for; without it the logic thread blocks
        // (VERIFIED).
        let sem = c.m.mem.read_u32(SWITCH_SEMAPHORE);
        if sem != 0 {
            let h = c.m.mem.read_u32(sem + 8);
            let release = c.m.mem.read_u32(IAT_RELEASE_SEMAPHORE);
            crate::call::call_stdcall(c.m, release, &[h, 1, 0]);
        }
        c.m.mem.write_u32(RES_REQUEST, 0xfa);
    }
    {
        let st = c.m.state::<ResState>();
        let mut s = st.borrow_mut();
        s.mode = Some(want_mode);
        s.applied = (!is_standard(want.0, want.1) || target.is_some()).then_some(want);
        s.anchor = None;
        s.anchor_map = false;
        s.redraw_frames = redraw_frames_after(cur, want);
        s.settle_frames = if ack { 0 } else { 6 };
        s.switches += 1;
        s.last_switch_ms = now;
    }
    if trace() {
        let esp = c.m.cpu().regs[ESP];
        eprintln!(
            "res: switch {}x{} -> {}x{} mode {}x{} ({}, variant {}, esp {esp:#x})",
            cur.0, cur.1, want.0, want.1, want_mode.0, want_mode.1, if fast { "fast" } else { "mode set" }, variant_for(want.1).index
        );
    }
    c.m.log(LogLevel::Info, &format!("res: {}x{} -> {}x{} ({})", cur.0, cur.1, want.0, want.1, if fast { "fast" } else { "mode set" }));
    // Skip this frame (what the game does after its own switch): al = 1, thiscall with one argument.
    c.return_from_function(1, 1)
}

/// Presented size = `size` (ddraw port extension `DDSDM_PORT_LOGICAL`, see s3-dx ddraw.rs).
fn set_logical(m: &mut Machine, size: (u32, u32)) {
    let dd = m.state::<ResState>().borrow_mut().ddraw2;
    if dd == 0 || !crate::ui_hud_game::readable(m, dd, 4) {
        return;
    }
    let vt = m.mem.read_u32(dd);
    let f = m.mem.read_u32(vt + 0x54);
    let r = crate::call::call_stdcall(m, f, &[dd, size.0, size.1, 16, 0, DDSDM_PORT_LOGICAL]);
    if r != 0 && trace() {
        eprintln!("res: logical size {}x{} rejected: {r:#x}", size.0, size.1);
    }
}

/// The view rectangles cached by the display setup (`0x42ef70..`): `gfx+0x5f6e8` and the landscape object's
/// `+0x58/+0x5c` (size) and `+0x74..+0x80` (rect).
fn update_view_rects(m: &mut Machine, gfx: u32) {
    let pw = m.mem.read_u32(L_PANEL_W);
    let top = m.mem.read_u32(0x007d_fd58);
    let (mw, mh) = (m.mem.read_u32(L_MAP_W), m.mem.read_u32(L_MAP_H));
    let rect = [pw, top, pw + mw, top + mh];
    for (i, v) in rect.iter().enumerate() {
        m.mem.write_u32(gfx + 0x5f6e8 + 4 * i as u32, *v);
    }
    let land = m.mem.read_u32(gfx + 0x5f6cc);
    if land != 0 && crate::ui_hud_game::readable(m, land, 0xa8) {
        m.mem.write_u32(land + 0x58, mw);
        m.mem.write_u32(land + 0x5c, mh);
        for (i, v) in rect.iter().enumerate() {
            m.mem.write_u32(land + 0x74 + 4 * i as u32, *v);
        }
    }
}

/// Was the logic thread's snapshot made for the current view size (`0x51f990..`: cols / rows)?
fn snapshot_matches(m: &Machine, snap: u32) -> bool {
    let cols = (m.mem.read_u32(L_MAP_W) + 23) / 16 + 10;
    let rows = (m.mem.read_u32(L_MAP_H) + 255) / 9 + 11;
    m.mem.read_u32(snap + 0x30) == cols && m.mem.read_u32(snap + 0x34) == rows
}

/// Update the cached view rectangles if they differ from the layout globals; true if something changed.
fn sync_view_rects(m: &mut Machine, gfx: u32) -> bool {
    let land = m.mem.read_u32(gfx + 0x5f6cc);
    if land == 0 || !crate::ui_hud_game::readable(m, land, 0xa8) {
        return false;
    }
    let pw = m.mem.read_u32(L_PANEL_W);
    let (mw, mh) = (m.mem.read_u32(L_MAP_W), m.mem.read_u32(L_MAP_H));
    if m.mem.read_u32(land + 0x58) == mw && m.mem.read_u32(land + 0x5c) == mh && m.mem.read_u32(land + 0x74) == pw {
        return false;
    }
    update_view_rects(m, gfx);
    if trace() {
        let f: Vec<String> = (0..14).map(|i| format!("{:x}", m.mem.read_u32(land + 0x50 + 4 * i))).collect();
        eprintln!("res: view rect synced: panel {pw} map {mw}x{mh}; landscape {land:#x} +0x50..: {}", f.join(" "));
    }
    true
}

/// Camera clamp of `0x51b4d0` done host-side (the logic acknowledgement is skipped on the fast path).
fn clamp_camera(m: &mut Machine, gd: Option<u32>) {
    let Some(g) = gd else { return };
    let world = m.mem.read_u32(g + 0x2d2d0) as i32;
    let mw = m.mem.read_u32(L_MAP_W) as i32;
    let mh = m.mem.read_u32(L_MAP_H) as i32;
    let (x, y) = (m.mem.read_u32(g + GD_CAM_X) as i32 as f32, m.mem.read_u32(g + GD_CAM_Y) as i32 as f32);
    let (nx, ny) = crate::touch_logic::clamp_camera(x, y, world, mw, mh);
    m.mem.write_u32(g + GD_CAM_X, nx as i32 as u32);
    m.mem.write_u32(g + GD_CAM_Y, ny as i32 as u32);
}

/// The HUD restores the panel with the original map width of the variant; with a custom width the map view must
/// be `screen - panel`.
fn fix_map_width(m: &mut Machine, sw: u32) {
    let pw = m.mem.read_u32(L_PANEL_W);
    if pw == 0 {
        return;
    }
    if let Some(v) = variant(m.mem.read_u32(L_RES)) {
        if pw == v.panel_w && m.mem.read_u32(L_MAP_W) != sw - pw {
            m.mem.write_u32(L_MAP_W, sw - pw);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn variants_and_layout() {
        assert_eq!(variant_for(480).index, 1);
        assert_eq!(variant_for(599).index, 1);
        assert_eq!(variant_for(600).index, 2);
        assert_eq!(variant_for(780).index, 3);
        assert_eq!(variant_for(360).index, 1);
        let l = layout_values(1480, 600);
        assert!(l.contains(&(L_MAP_W, 1480 - 176)));
        assert!(l.contains(&(L_RES, 2)));
        // The original sizes reproduce the game's own table.
        for v in VARIANTS {
            let l = layout_values(v.w, v.h);
            let map_w = l.iter().find(|e| e.0 == L_MAP_W).unwrap().1;
            assert_eq!(map_w, [504, 624, 808][v.index as usize - 1]);
        }
    }

    #[test]
    fn grid_budget() {
        // 1024x768 (map 808x768): 123 columns of the original 130 (+3 neighbour reads).
        assert_eq!(grid_columns_needed(808, 768), 126);
        assert!(grid_rows_needed(768) <= 129);
        // Every size we allow fits the enlarged grid and sprite lists.
        assert!(grid_columns_needed(MAX_W, MAX_H) <= SNAP_COLS);
        assert!(grid_rows_needed(MAX_H) < SNAP_ROWS, "{}", grid_rows_needed(MAX_H));
        assert!(sprite_buckets_needed(MAX_H) <= SPRITE_BUCKETS, "{}", sprite_buckets_needed(MAX_H));
        // The game's 250 buckets were too few already at 780 (rows >= 125 lost their objects).
        assert!(sprite_buckets_needed(780) > ORIG_BUCKETS);
        assert_eq!(clamp_size(2229, 904), (2224, 904));
        assert_eq!(clamp_size(4000, 2000), (MAX_W, MAX_H));
        assert_eq!(clamp_size(100, 100), (MIN_W, MIN_H));
        assert!(is_standard(800, 600) && !is_standard(1480, 600));
    }

    #[test]
    fn snapshot_sites_sane() {
        assert_eq!(SNAP_TAIL_SITES.len(), 55);
        for &(a, off, v) in SNAP_TAIL_SITES {
            assert!((0x401000..0x650000).contains(&a) && off <= 3);
            assert!((SNAP_TAIL..=SNAP_SIZE).contains(&v) || (a, v) == (0x51f1f8, 0xc636c), "{a:#x}");
        }
        // The grid of SNAP_COLS x SNAP_ROWS cells ends exactly where the moved tail starts.
        assert_eq!(SNAP_GRID + SNAP_COLS * SNAP_COL_BYTES_NEW, SNAP_TAIL + snap_delta());
        assert_eq!(SNAP_GRID + 130 * SNAP_COL_BYTES, SNAP_TAIL);
        // shl 6 -> 7 turns (c<<6 + c)*2 = c*130 into c*258.
        assert_eq!(((1u32 << 7) + 1) * 2, SNAP_ROWS);
        for (_, _, v, n) in STRIDE_DISP_SITES {
            // n columns + a small row/field offset (+ the grid base 0x500 for the cell-pointer displacements).
            let rest = (v as i32 - n * SNAP_COL_BYTES as i32).rem_euclid(SNAP_COL_BYTES as i32);
            assert!(rest <= 0x500 + 0x95, "{v:#x}");
        }
        // No address is patched twice; patches do not overlap.
        let mut p: Vec<(u32, usize)> = code_patches().iter().map(|(a, o, _)| (*a, o.len())).collect();
        p.sort();
        for w in p.windows(2) {
            assert!(w[0].0 + w[0].1 as u32 <= w[1].0, "{:#x} {:#x}", w[0].0, w[1].0);
        }
        assert_eq!(p.len(), 55 + 10 + 2 + 30 + 74 + 1);
        assert_eq!(sprite_site_value(0x13a8c), GFX_SIZE);
        assert_eq!(sprite_site_value(0x5f19c), GFX_SIZE + 5 * SPRITE_BUCKETS * 4);
        assert_eq!(sprite_site_value(0xfb), SPRITE_BUCKETS + 1);
        assert_eq!(sprite_site_value(0xfa), SPRITE_BUCKETS);
    }
}
