//! Custom game resolutions for the GOG S3.EXE (res-zoom, docs/porting/resolution-zoom.md).
//!
//! The original game knows three layouts (640x480, 800x600, 1024x768; `0x4c6d70` / runtime switch `0x4c7490`).
//! This module lets the game run at any size `W x H` (`MIN_W..=MAX_W` x `MIN_H..=MAX_H`) while a game is running:
//!
//! - **Render snapshot grid** (`[logic+0x3d0]`, allocated once by `0x51f110`, size `0xc7720`): the logic thread
//!   copies the visible tiles into a grid of 130 rows x 130 columns (`snap+0x500`, 0x30 bytes per tile,
//!   index `row + col*130`). Because the map rows are sheared, a view needs `cols + rows/2` columns
//!   (`cols = (mapW+23)/16+10`, `rows = (mapH+255)/9+11`, `0x51f990..`); 1024x768 already uses 123 of 130.
//!   [`patch_snapshot`] moves the fields behind the grid (`0xc65c0..0xc7720`, 55 code sites listed in
//!   [`SNAP_TAIL_SITES`], generated by `tools/res-zoom/snap_sites.py` + 4 found by res-tall) so the grid gets
//!   [`SNAP_COLS`] columns, and changes the row stride 130 to [`SNAP_ROWS`] (res-tall, 2026-11-08): the ten
//!   `x*130` index computations ([`STRIDE_SHL_SITES`]), the column steps and neighbour displacements
//!   ([`STRIDE_DISP_SITES`], [`STRIDE_INDEX_SITES`]).
//! - **Sprite lists** of the frame renderer (`gfx+0x20c..`, buckets = 2 per snapshot row, 250 buckets): the
//!   bucket arrays move behind the `gfx` object (allocation `0x42c6b9` grows) and get [`SPRITE_BUCKETS`] entries
//!   ([`SPRITE_SITES`]); with 250 the objects of rows >= 125 were not drawn.
//! - **Landscape ring buffer** (`0x54bec0`) and **text DIB** (`0x4a78f0`) are sized once at game start (display
//!   setup `0x42e430`) from the screen; [`install`] makes them [`MAX_W`] x [`MAX_H`] so any later size fits (the
//!   F1-F3 switch never re-created them: the black band of the HUD after a runtime switch).
//! - **Mode set**: the game posts `0x804(index)` and `0x405c80` calls `SetDisplayMode` with 640/800/1024 constants;
//!   the call sites `0x405cc3` / `0x405cf2` get the custom size when `0x42ce90` was asked for a non-standard size.
//! - **Switch**: a hook at `0x4c7490` entry (render thread, once per in-game frame) does what the F1-F3 switch does
//!   with custom numbers: write the layout globals ([`write_layout`]), `0x42ce90(W, H, 16, 0, 0)` on `gfx`,
//!   `[0x7dfd44] = 0xfa` (the logic thread then forces a full landscape redraw and clamps the camera, `0x53db67`)
//!   and skips the frame.
//!
//! Panel art, minimap and panel grid keep the values of the "variant" (1..3 = the original layout whose height
//! fits, [`variant_for`]); the map view takes the rest of the screen. Nothing here touches simulation state (the
//! game itself supports different resolutions per multiplayer peer); see resolution-zoom.md for the MP check.

