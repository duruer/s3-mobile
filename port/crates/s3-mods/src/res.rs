/// Bytes the fields behind the grid move by (the grid becomes `SNAP_COLS x SNAP_ROWS` cells).
pub const fn snap_delta() -> u32 {
    SNAP_GRID + SNAP_COLS * SNAP_COL_BYTES_NEW - SNAP_TAIL
}

